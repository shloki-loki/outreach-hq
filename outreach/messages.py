"""Drafts: creating them and refusing bad ones.

Every email an agent writes passes `check_draft` before it can reach the approval queue. The checks
are the written rules from config/voice.md turned into code, so a slip in an agent's wording is
caught here and not in someone's inbox.
"""

from __future__ import annotations

import re
from typing import Any

from . import store
from .util import load_config, now_iso, parse_iso, now, word_match

KINDS = ("cold", "followup1", "followup2")
LIMITS = {"cold": (50, 120), "followup1": (20, 70), "followup2": (20, 70)}
PLAYS = ("question", "offer", "direct", "story")   # config/voice.md, "The four plays"
LINKEDIN_KINDS = ("connect", "inmail")

BANNED = [
    (r"hope (this|you|the|your)[^.]{0,40}(find|well|great|good)", "filler opener (\"hope this finds you well\")"),
    (r"\bI came across (your|the)\b", "filler opener (\"I came across your profile\")"),
    (r"\bjust (bumping|following up|checking in|circling back)\b|\bcircling back\b|\bbumping this\b", "guilt-trip follow-up phrasing"),
    (r"\b(passionate|synergy|synergies|rockstar|ninja|guru|leverage my|dynamic professional|esteemed|delve|thrilled|excited to apply)\b", "buzzword"),
    (r"\b(to whom it may concern|dear sir|dear madam|respected sir|respected ma'?am)\b", "generic salutation"),
    (r"\b(ctc|lpa|salary|compensation|notice period)\b", "pay or notice period in a cold email"),
    (r"\b(as an ai|language model|generated by|automated message|this email was sent by)\b", "mentions automation"),
    (r"!", "exclamation mark"),
    (r"[\u2600-\u27bf\U0001F300-\U0001FAFF]", "emoji"),
    (r"\[[A-Za-z _]+\]|\{[A-Za-z _]+\}|<[A-Za-z _]+>|XX+", "unfilled placeholder"),
    (r"\bkindly\b|\bdo the needful\b|\bplease find attached herewith\b", "stiff phrasing"),
    (r"\u2014", "em dash (reads as machine-written; use a comma or full stop)"),
    # playbook v2 (config/voice.md, Hard rules)
    (r"\bI would like to be considered\b|\bI'?d like to be considered\b", "banned phrase (\"would like to be considered\")"),
    (r"\bI am writing to\b|\bI'?m writing to\b", "banned phrase (\"I am writing to\")"),
    (r"\bI'?d love to\b|\bI would love to\b", "banned phrase (\"I'd love to\")"),
    (r"\bexcit(ed|ing)\b", "banned word (\"excited\")"),
    (r"\bkeen to\b", "banned phrase (\"keen to\")"),
    (r"\bresonat(es|ed|e)\b", "banned word (\"resonates\")"),
    (r"\b(great|perfect|good|strong|natural) fit\b", "banned phrase (\"great fit\")"),
    (r"\bpick your brain\b|\btouch base\b|\breach(ing)? out\b|\bmy name is\b", "banned phrase (pick your brain, touch base, reaching out, my name is)"),
    (r"\bquick (call|chat)\b|\b15[- ]min(ute)?s?\b|\bfifteen minutes\b|\bhop on\b", "banned ask (quick call, 15 minutes, hop on)"),
    (r"\bhere'?s the thing\b", "banned phrase (\"Here's the thing\")"),
    (r"\b(it'?s|this is|that'?s|it is) not (just |only |about )?[^.?\n]{1,60}[,;] (it'?s|it is|but)\b", "the \"It's not X, it's Y\" shape"),
    (r"\bthe (result|answer|outcome|kicker|catch)\?", "the \"The result? ...\" shape"),
]

# Stiff forms where a contraction reads like a person (voice.md: "Use contractions").
STIFF = re.compile(r"\b(I am|do not|did not|does not|cannot|can not|it is|that is|I will|I would|you are|we are|"
                   r"there is|I have (been|built|run|done|worked|led|seen|spent|had|taken|shipped|managed))\b", re.I)
CONTRACTION = re.compile(r"\b\w+['\u2019](m|ve|d|ll|re|s|t)\b", re.I)
SELF_DISQUALIFY = re.compile(
    r"\b(i (don'?t|do not) have (an )?mba|without an mba|(if|in case) you (need|want|are looking for) someone (more )?(senior|experienced)|"
    r"i (know|realise|realize|understand) i('?m| am) (junior|not|young|early)|may not (be|have) (the )?(perfect|ideal|exact|required|enough)|"
    r"i lack|(don'?t|do not) have (much|enough|the required) experience|limited experience|only (1\.3|one) years?|"
    r"not (a|the) (perfect|ideal|typical) (fit|candidate|profile))\b", re.I)
EXPERIENCE_CLAIM = re.compile(r"\b(\d+(?:\.\d+)?)\+?\s*(?:years?|yrs?)\s+(?:of\s+)?(?:work\s+|full[- ]time\s+|professional\s+)?"
                              r"(?:experience|in (?:operations|strategy|supply chain|product))\b", re.I)
NUMBER = re.compile(r"(?<![\w.])\d+(?:[.,]\d+)*%?")
FIRST_SENTENCE_BANNED = re.compile(r"^\s*(I\b|I'|I\u2019|My\b|Your post(ing)?\b|The role\b)", re.I)


def word_count(text: str) -> int:
    return len(re.findall(r"\b[\w'’-]+\b", text))


APPLIED_CLAIM = re.compile(r"\b(i have applied|i've applied|i’ve applied|i applied|have already applied|"
                           r"applied (for|to|via|through|on)|submitted my application)\b", re.I)
OPENING_CLAIM = re.compile(r"\b(your|the) (opening|open role|job post|job posting|posting|listing|vacancy|advert(isement)?)\b|"
                           r"\b(saw|noticed|came across) (your|the|that you).{0,40}\b(hiring|opening|role)\b", re.I)


def _after_greeting(body: str) -> str:
    """The body without its greeting line and sign-off, for sentence-level rules."""
    lines = body.strip().splitlines()
    if lines and re.match(r"\s*(hi|hello|hey)\b[^\n]{0,40},?\s*$", lines[0], re.I):
        lines = lines[1:]
    return "\n".join(lines).strip()


def _common(text: str, body: str, problems: list[str]) -> None:
    profile = load_config("profile")
    for pattern, label in BANNED:
        if re.search(pattern, text, re.I):
            problems.append(f"contains {label}")
    for hidden in profile["positioning"]["hide_in_messages"]:
        if word_match(hidden, text):
            problems.append(f"mentions {hidden}, which must stay out of messages")
    if re.search(r"https?://|www\.", body):
        problems.append("contains a link; the portfolio link is added by the signature")
    stiff = sorted({m.group(0) for m in STIFF.finditer(body)}, key=str.lower)
    if stiff:
        problems.append("stiff forms; use contractions instead of: " + ", ".join(f'"{s}"' for s in stiff[:4]))
    for match in EXPERIENCE_CLAIM.finditer(body):
        if float(match.group(1)) > 1.5:
            problems.append(f"claims \"{match.group(0)}\"; Shlok has about 1.3 years")


def check_draft(kind: str, subject: str, body: str, *, to_name: str = "", company: str = "",
                speculative: bool = False, applied: bool | None = None, play: str | None = None,
                hook: str | None = None, hook_source: str | None = None, promise: str | None = None,
                v2: bool = True) -> list[str]:
    """Returns the list of problems; empty means the draft may be queued.

    `v2=False` is only for re-checking drafts written before playbook v2 (2026-11-14); every new draft
    is checked with v2."""
    problems: list[str] = []
    profile = load_config("profile")
    if kind not in KINDS:
        return [f"unknown kind '{kind}'"]
    low, high = LIMITS[kind]
    words = word_count(body)
    if not low <= words <= high:
        problems.append(f"body is {words} words; a {kind} email must be {low}-{high}")
    if kind == "cold":
        subject_words = word_count(subject)
        if not 2 <= subject_words <= 6:
            problems.append(f"subject is {subject_words} words; keep it to 2-6")
        if len(subject) > 45:
            problems.append(f"subject is {len(subject)} characters; keep it to 45")
        if re.search(r"\||\d|application for", subject, re.I):
            problems.append("subject has a pipe, a number or \"application for\"")
    if subject != subject.strip() or subject.isupper():
        problems.append("subject has stray spaces or is all capitals")
    text = f"{subject}\n{body}"
    _common(text, body, problems)
    first = profile["person"]["first_name"]
    lines = body.rstrip().splitlines()
    if not lines or lines[-1].strip() != first:
        problems.append(f"body must end with a line that is just \"{first}\" (the signature is added on send)")
    if to_name:
        first_name = to_name.split()[0]
        if kind == "cold" and not re.match(rf"\s*(hi|hello|hey)\s+{re.escape(first_name)}\b", body, re.I):
            problems.append(f"must open with \"Hi {first_name},\"")
    elif kind == "cold" and not re.match(r"\s*(hi|hello)\b", body, re.I):
        problems.append("must open with a greeting")
    unnamed = bool(re.match(r"\s*(undisclosed|unnamed|confidential|stealth)\b", company or "", re.I))
    if company and not unnamed and kind == "cold" and not word_match(company.split("(")[0].strip().split()[0], text):
        problems.append(f"never names the company ({company}); a cold email must be specific to it")
    if APPLIED_CLAIM.search(text) and (speculative or applied is False):
        problems.append("says he has applied, but " + ("there is no opening to apply to" if speculative
                        else "the lead is not marked applied; say which role he wants to be considered for"))
    if speculative and OPENING_CLAIM.search(text):
        problems.append("refers to an opening, but this company has no named opening; write it as a speculative note")
    if not v2:
        return problems
    content = _after_greeting(body)
    questions = body.count("?")
    numbers = len(NUMBER.findall(content))
    if numbers > 4:
        problems.append(f"{numbers} numbers in the body; at most 4, so results are not stacked")
    if kind == "cold":
        if questions != 1:
            problems.append(f"{questions} question marks; a first email asks exactly one question")
        if FIRST_SENTENCE_BANNED.match(content) and play != "direct":  # a recruiter gets the role up front
            problems.append("first sentence starts with I, My, \"Your post\" or \"The role\"; open on their world")
        if SELF_DISQUALIFY.search(body):
            problems.append("self-disqualifying line in a first email; the easy no belongs in the last follow-up")
        if not CONTRACTION.search(body):
            problems.append("no contractions (I'm, I've, didn't); it reads stiff")
        if play not in PLAYS:
            problems.append(f"play must be one of {', '.join(PLAYS)} (config/voice.md)")
        if speculative and play and play != "offer":
            problems.append("a note to a company with no opening uses the offer play")
        if play == "offer" and not (promise or "").strip():
            problems.append("the offer play needs --promise: what Shlok will deliver if they say yes")
        if not (hook or "").strip() or len((hook or "").strip()) < 20:
            problems.append("needs the hook: the specific, true fact about them the opener is built on")
        if not re.match(r"https?://\S+$", (hook_source or "").strip()):
            problems.append("needs hook_source: the URL where the hook was read (no source, no draft)")
    elif questions > 1:
        problems.append(f"{questions} question marks; a follow-up asks at most one")
    return problems


def check_cover_note(text: str, *, company: str = "") -> list[str]:
    """The short 'why this role' note pasted into an application form (written for Shlok to submit himself)."""
    problems: list[str] = []
    words = word_count(text)
    if not 60 <= words <= 150:
        problems.append(f"cover note is {words} words; 60-150")
    if company and not word_match(company.split("(")[0].strip(), text):
        problems.append(f"does not name {company}")
    if re.match(r"\s*(i|my|i'm|i am)\b", text, re.I):
        problems.append("opens on himself; open on what they are building or what the role needs")
    _common(text, text, problems)
    if SELF_DISQUALIFY.search(text):
        problems.append("self-disqualifying line")
    if len(NUMBER.findall(text)) > 4:
        problems.append("more than 4 numbers")
    if re.search(r"\b(ctc|lpa|notice period|salary)\b", text, re.I):
        problems.append("mentions pay or notice period")
    return problems


def check_linkedin(kind: str, text: str, *, to_name: str = "", company: str = "", subject: str = "") -> list[str]:
    """A LinkedIn note or InMail, drafted for Shlok to copy and send by hand (voice.md, LinkedIn)."""
    problems: list[str] = []
    if kind not in LINKEDIN_KINDS:
        return [f"unknown LinkedIn kind '{kind}'"]
    if kind == "connect":
        if len(text) > 200:
            problems.append(f"connection note is {len(text)} characters; at most 200")
        if text.count("?") > 1:
            problems.append("a connection note asks nothing beyond connecting")
    else:
        words = word_count(text)
        if not 40 <= words <= 80:
            problems.append(f"message is {words} words; 40-80")
        if text.count("?") != 1:
            problems.append(f"{text.count('?')} question marks; a message asks exactly one question")
        if not 1 <= word_count(subject) <= 4:
            problems.append("an InMail needs a subject of 1-4 words")
    if to_name and not re.match(rf"\s*(hi|hello|hey)\s+{re.escape(to_name.split()[0])}\b", text, re.I):
        problems.append(f"must open with \"Hi {to_name.split()[0]},\"")
    _common(f"{subject}\n{text}", text, problems)
    if SELF_DISQUALIFY.search(text):
        problems.append("self-disqualifying line")
    if len(NUMBER.findall(text)) > 3:
        problems.append("more than 3 numbers")
    if APPLIED_CLAIM.search(text):
        problems.append("claims an application; LinkedIn notes never do")
    return problems


def suppressed(email: str) -> str | None:
    """Why this address must not be emailed, or None."""
    entry = store.load("suppression")["emails"].get(email.lower())
    return entry.get("reason") if entry else None


def recently_contacted(email: str, messages: list[dict], days: int) -> bool:
    for message in messages:
        if message.get("to", "").lower() == email.lower() and message.get("kind") == "cold" \
                and message.get("status") in ("sent", "replied", "sending", "approved", "draft"):
            sent = parse_iso(message.get("sent_at") or message.get("created_at"))
            if sent and (now() - sent).days < days:
                return True
    return False


TRUSTED = ("published", "verified", "hunter", "pattern")


def create_draft(lead_id: str, contact_id: str, kind: str, subject: str, body: str, *, hook: str = "",
                 hook_source: str = "", created_by: str = "send-track", attach_resume: bool = False,
                 allow_unverified: bool = False, play: str | None = None, promise: str = "") -> dict[str, Any]:
    """Validate and queue a draft for approval. Raises ValueError listing every problem."""
    settings = load_config("settings")
    outcome: dict[str, Any] = {}

    def change() -> None:
        outcome.clear()
        leads, data = store.load("leads"), store.load("messages")
        lead = store.find(leads["leads"], lead_id)
        if not lead:
            raise ValueError(f"no lead {lead_id}")
        contact = store.find(lead.get("contacts", []), contact_id)
        if not contact:
            raise ValueError(f"lead {lead_id} has no contact {contact_id}")
        problems = []
        email = (contact.get("email") or "").lower()
        if not email:
            problems.append(f"{contact.get('name')} has no email address yet; run find-email first")
        elif contact.get("email_status") in ("bounced", "invalid"):
            problems.append(f"{email} is marked {contact['email_status']}")
        elif suppressed(email):
            problems.append(f"{email} is on the do-not-email list: {suppressed(email)}")
        elif kind == "cold" and contact.get("email_status") not in TRUSTED and not allow_unverified:
            problems.append(f"{email} is an unverified {contact.get('email_status')}; verify it first "
                            f"(find-email --lead {lead_id} --recheck). Only for a top lead with no better "
                            f"address, pass --allow-unverified (at most 2 a day are sent)")
        mine = [m for m in data["messages"] if m.get("lead_id") == lead_id]
        thread_parent = None
        if kind == "cold":
            if email and recently_contacted(email, data["messages"], settings["sending"]["one_email_per_person_days"]):
                problems.append(f"{email} already has a cold email in the last "
                                f"{settings['sending']['one_email_per_person_days']} days")
            emailed = {m["contact_id"] for m in mine if m.get("kind") == "cold" and m.get("status") != "skipped"}
            if contact_id not in emailed and len(emailed) >= settings["sending"]["max_contacts_per_company"]:
                problems.append(f"lead already has cold emails to {len(emailed)} people (the cap)")
        else:
            previous = [m for m in mine if m.get("contact_id") == contact_id and m.get("status") == "sent"]
            cold = next((m for m in previous if m.get("kind") == "cold"), None)
            if not cold:
                problems.append("no sent cold email to follow up on")
            elif kind == "followup2" and not any(m.get("kind") == "followup1" for m in previous):
                problems.append("followup2 needs a sent followup1 first")
            else:
                thread_parent = cold.get("message_id")
            if any(m.get("contact_id") == contact_id and m.get("kind") == kind and m.get("status") != "skipped" for m in mine):
                problems.append(f"a {kind} for this person already exists")
            if any(m.get("contact_id") == contact_id and m.get("status") == "replied" for m in mine) or lead.get("replied_at"):
                problems.append("they already replied; no follow-up")
        if lead.get("stage") in ("rejected", "skipped") or lead.get("outcome") in ("rejected", "closed"):
            problems.append("lead is closed")
        speculative = lead.get("type") == "company"
        problems += check_draft(kind, subject, body, to_name=contact.get("name") or "", company=lead.get("company") or "",
                                speculative=speculative, applied=bool(lead.get("applied_at")), play=play,
                                hook=hook, hook_source=hook_source, promise=promise)
        if problems:
            raise ValueError("; ".join(problems))
        message = {
            "id": store.next_id(data["messages"], "M"), "lead_id": lead_id, "contact_id": contact_id,
            "to": email, "to_name": contact.get("name") or "", "kind": kind,
            "subject": subject if kind == "cold" else f"Re: {_root_subject(mine, contact_id) or subject}",
            "body": body.rstrip() + "\n", "status": "draft", "email_status": contact.get("email_status"),
            "speculative": speculative,
            "hook": hook, "hook_source": hook_source, "play": play, "promise": promise, "playbook": "v2",
            "attach_resume": attach_resume,
            "created_at": now_iso(), "created_by": created_by, "approved_at": None, "sending_at": None,
            "sent_at": None, "message_id": None, "thread_parent": thread_parent, "error": None, "reply": None,
        }
        data["messages"].append(message)
        if kind != "cold":
            lead["followup"] = {"due": False, "kind": None, "since": None}
        store.add_timeline(lead, created_by, "drafted", f"{kind} email to {contact.get('name')} awaiting approval")
        store.save("messages", data)
        store.save("leads", leads)
        outcome.update(message)

    store.transact(change, f"draft: {kind} for {lead_id}")
    return outcome


def _root_subject(messages: list[dict], contact_id: str) -> str | None:
    cold = next((m for m in messages if m.get("contact_id") == contact_id and m.get("kind") == "cold"
                 and m.get("status") == "sent"), None)
    return re.sub(r"(?i)^(re:\s*)+", "", cold["subject"]) if cold else None
