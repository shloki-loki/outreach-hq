"""Drafts: creating them and refusing bad ones.

Every email an agent writes passes `check_draft` before it can reach the approval queue. The checks
are the written rules from config/voice.md turned into code, so a slip in an agent's wording is
caught here and not in someone's inbox.
"""

from __future__ import annotations

import re
from typing import Any

from . import store
from .util import load_config, now_iso, parse_iso, now, word_match

KINDS = ("cold", "followup1", "followup2")
LIMITS = {"cold": (50, 150), "followup1": (20, 80), "followup2": (15, 70)}

BANNED = [
    (r"hope (this|you|the|your)[^.]{0,40}(find|well|great|good)", "filler opener (\"hope this finds you well\")"),
    (r"\bI came across (your|the)\b", "filler opener (\"I came across your profile\")"),
    (r"\bjust (bumping|following up|checking in|circling back)\b|\bcircling back\b|\bbumping this\b", "guilt-trip follow-up phrasing"),
    (r"\b(passionate|synergy|synergies|rockstar|ninja|guru|leverage my|dynamic professional|esteemed|delve|thrilled|excited to apply)\b", "buzzword"),
    (r"\b(to whom it may concern|dear sir|dear madam|respected sir|respected ma'?am)\b", "generic salutation"),
    (r"\b(ctc|lpa|salary|compensation|notice period)\b", "pay or notice period in a cold email"),
    (r"\b(as an ai|language model|generated by|automated message|this email was sent by)\b", "mentions automation"),
    (r"!", "exclamation mark"),
    (r"[☀-➿\U0001F300-\U0001FAFF]", "emoji"),
    (r"\[[A-Za-z _]+\]|\{[A-Za-z _]+\}|<[A-Za-z _]+>|XX+", "unfilled placeholder"),
    (r"\bkindly\b|\bdo the needful\b|\bplease find attached herewith\b", "stiff phrasing"),
    (r"—", "em dash (reads as machine-written; use a comma or full stop)"),
]


def word_count(text: str) -> int:
    return len(re.findall(r"\b[\w'’-]+\b", text))


def check_draft(kind: str, subject: str, body: str, *, to_name: str = "", company: str = "") -> list[str]:
    """Returns the list of problems; empty means the draft may be queued."""
    problems: list[str] = []
    profile = load_config("profile")
    if kind not in KINDS:
        return [f"unknown kind '{kind}'"]
    low, high = LIMITS[kind]
    words = word_count(body)
    if not low <= words <= high:
        problems.append(f"body is {words} words; a {kind} email must be {low}-{high}")
    subject_words = word_count(subject)
    if kind == "cold" and not 2 <= subject_words <= 9:
        problems.append(f"subject is {subject_words} words; keep it to 2-9")
    if subject != subject.strip() or subject.isupper():
        problems.append("subject has stray spaces or is all capitals")
    text = f"{subject}\n{body}"
    for pattern, label in BANNED:
        if re.search(pattern, text, re.I):
            problems.append(f"contains {label}")
    for hidden in profile["positioning"]["hide_in_messages"]:
        if word_match(hidden, text):
            problems.append(f"mentions {hidden}, which must stay out of messages")
    first = profile["person"]["first_name"]
    lines = body.rstrip().splitlines()
    if not lines or lines[-1].strip() != first:
        problems.append(f"body must end with a line that is just \"{first}\" (the signature is added on send)")
    if to_name:
        first_name = to_name.split()[0]
        if kind == "cold" and not re.match(rf"\s*(hi|hello|hey)\s+{re.escape(first_name)}\b", body, re.I):
            problems.append(f"must open with \"Hi {first_name},\"")
    elif kind == "cold" and not re.match(r"\s*(hi|hello)\b", body, re.I):
        problems.append("must open with a greeting")
    if company and kind == "cold" and not word_match(company.split("(")[0].strip().split()[0], text):
        problems.append(f"never names the company ({company}); a cold email must be specific to it")
    if re.search(r"https?://", body):
        problems.append("contains a link; the portfolio link is added by the signature")
    return problems


def suppressed(email: str) -> str | None:
    """Why this address must not be emailed, or None."""
    entry = store.load("suppression")["emails"].get(email.lower())
    return entry.get("reason") if entry else None


def recently_contacted(email: str, messages: list[dict], days: int) -> bool:
    for message in messages:
        if message.get("to", "").lower() == email.lower() and message.get("kind") == "cold" \
                and message.get("status") in ("sent", "replied", "sending", "approved", "draft"):
            sent = parse_iso(message.get("sent_at") or message.get("created_at"))
            if sent and (now() - sent).days < days:
                return True
    return False


def create_draft(lead_id: str, contact_id: str, kind: str, subject: str, body: str, *, hook: str = "",
                 hook_source: str = "", created_by: str = "send-track", attach_resume: bool = False) -> dict[str, Any]:
    """Validate and queue a draft for approval. Raises ValueError listing every problem."""
    settings = load_config("settings")
    outcome: dict[str, Any] = {}

    def change() -> None:
        outcome.clear()
        leads, data = store.load("leads"), store.load("messages")
        lead = store.find(leads["leads"], lead_id)
        if not lead:
            raise ValueError(f"no lead {lead_id}")
        contact = store.find(lead.get("contacts", []), contact_id)
        if not contact:
            raise ValueError(f"lead {lead_id} has no contact {contact_id}")
        problems = []
        email = (contact.get("email") or "").lower()
        if not email:
            problems.append(f"{contact.get('name')} has no email address yet; run find-email first")
        elif contact.get("email_status") in ("bounced", "invalid"):
            problems.append(f"{email} is marked {contact['email_status']}")
        elif suppressed(email):
            problems.append(f"{email} is on the do-not-email list: {suppressed(email)}")
        mine = [m for m in data["messages"] if m.get("lead_id") == lead_id]
        thread_parent = None
        if kind == "cold":
            if email and recently_contacted(email, data["messages"], settings["sending"]["one_email_per_person_days"]):
                problems.append(f"{email} already has a cold email in the last "
                                f"{settings['sending']['one_email_per_person_days']} days")
            emailed = {m["contact_id"] for m in mine if m.get("kind") == "cold" and m.get("status") != "skipped"}
            if contact_id not in emailed and len(emailed) >= settings["sending"]["max_contacts_per_company"]:
                problems.append(f"lead already has cold emails to {len(emailed)} people (the cap)")
        else:
            previous = [m for m in mine if m.get("contact_id") == contact_id and m.get("status") == "sent"]
            cold = next((m for m in previous if m.get("kind") == "cold"), None)
            if not cold:
                problems.append("no sent cold email to follow up on")
            elif kind == "followup2" and not any(m.get("kind") == "followup1" for m in previous):
                problems.append("followup2 needs a sent followup1 first")
            else:
                thread_parent = cold.get("message_id")
            if any(m.get("contact_id") == contact_id and m.get("kind") == kind and m.get("status") != "skipped" for m in mine):
                problems.append(f"a {kind} for this person already exists")
            if any(m.get("contact_id") == contact_id and m.get("status") == "replied" for m in mine) or lead.get("replied_at"):
                problems.append("they already replied; no follow-up")
        if lead.get("stage") in ("rejected", "skipped") or lead.get("outcome") in ("rejected", "closed"):
            problems.append("lead is closed")
        problems += check_draft(kind, subject, body, to_name=contact.get("name") or "", company=lead.get("company") or "")
        if problems:
            raise ValueError("; ".join(problems))
        message = {
            "id": store.next_id(data["messages"], "M"), "lead_id": lead_id, "contact_id": contact_id,
            "to": email, "to_name": contact.get("name") or "", "kind": kind,
            "subject": subject if kind == "cold" else f"Re: {_root_subject(mine, contact_id) or subject}",
            "body": body.rstrip() + "\n", "status": "draft", "email_status": contact.get("email_status"),
            "hook": hook, "hook_source": hook_source, "attach_resume": attach_resume,
            "created_at": now_iso(), "created_by": created_by, "approved_at": None, "sending_at": None,
            "sent_at": None, "message_id": None, "thread_parent": thread_parent, "error": None, "reply": None,
        }
        data["messages"].append(message)
        if kind != "cold":
            lead["followup"] = {"due": False, "kind": None, "since": None}
        store.add_timeline(lead, created_by, "drafted", f"{kind} email to {contact.get('name')} awaiting approval")
        store.save("messages", data)
        store.save("leads", leads)
        outcome.update(message)

    store.transact(change, f"draft: {kind} for {lead_id}")
    return outcome


def _root_subject(messages: list[dict], contact_id: str) -> str | None:
    cold = next((m for m in messages if m.get("contact_id") == contact_id and m.get("kind") == "cold"
                 and m.get("status") == "sent"), None)
    return re.sub(r"(?i)^(re:\s*)+", "", cold["subject"]) if cold else None
